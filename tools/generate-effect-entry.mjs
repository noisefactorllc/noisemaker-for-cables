#!/usr/bin/env node

import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { validateManifest, verifyArtifactLock } from './lib/artifact-lock.js'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const cacheRoot = resolve(projectRoot, 'vendor-cache')
const lockPath = resolve(projectRoot, 'vendor.lock.json')
const manifestPath = resolve(cacheRoot, 'effects/manifest.json')
const outputPath = resolve(projectRoot, 'src/generated/register-all-effects.js')

const compareStrings = (left, right) => (left < right ? -1 : left > right ? 1 : 0)

function effectIdFromArtifactPath(path) {
  return path.slice('effects/'.length, -'.js'.length)
}

function assertSameIds(lockedIds, manifestIds) {
  if (
    lockedIds.length !== manifestIds.length ||
    lockedIds.some((effectId, index) => effectId !== manifestIds[index])
  ) {
    const locked = new Set(lockedIds)
    const manifest = new Set(manifestIds)
    const missing = manifestIds.filter((effectId) => !locked.has(effectId))
    const extra = lockedIds.filter((effectId) => !manifest.has(effectId))
    throw new Error(
      `Generated effect import mismatch: missing [${missing.join(', ')}], extra [${extra.join(', ')}]`,
    )
  }
}

function renderEntry(effectIds) {
  const imports = effectIds.map(
    (effectId, index) =>
      `import effect${index} from '../../vendor-cache/effects/${effectId}.js'`,
  )
  const entries = effectIds.map((effectId, index) => `  ['${effectId}', effect${index}],`)
  const metadataEntries = effectIds.map((effectId) => `  '${effectId}',`)

  return [
    '// Generated by tools/generate-effect-entry.mjs. Do not edit by hand.',
    "import { createEffectBatchRegistrar } from '../runtime/register-batch.js'",
    "import { bootCore, finalizeEnums, registerEffectInstance } from '../runtime/register-effect.js'",
    '',
    ...imports,
    '',
    `export const effectCount = ${effectIds.length}`,
    'export const effectIds = Object.freeze([',
    ...metadataEntries,
    '])',
    '',
    'const effects = [',
    ...entries,
    ']',
    '',
    'const registerEffectBatch = createEffectBatchRegistrar(effects, {',
    '  bootCore,',
    '  finalizeEnums,',
    '  registerEffectInstance,',
    '})',
    '',
    'export function registerAllEffects(core) {',
    '  return registerEffectBatch(core)',
    '}',
    '',
  ].join('\n')
}

async function writeAtomic(path, source) {
  await mkdir(dirname(path), { recursive: true })
  const temporaryPath = `${path}.tmp-${process.pid}`
  await writeFile(temporaryPath, source)
  await rename(temporaryPath, path)
}

async function main() {
  const verified = await verifyArtifactLock({ cacheRoot, lockPath })
  const lock = JSON.parse(await readFile(lockPath, 'utf8'))
  const manifestIds = validateManifest(await readFile(manifestPath)).sort(compareStrings)
  const lockedIds = lock.artifacts
    .map((artifact) => artifact.path)
    .filter((path) => path.startsWith('effects/') && path.endsWith('.js'))
    .map(effectIdFromArtifactPath)
    .sort(compareStrings)

  assertSameIds(lockedIds, manifestIds)
  if (lock.effectCount !== lockedIds.length || verified.effectCount !== lockedIds.length) {
    throw new Error(
      `Generated effect count mismatch: lock ${lock.effectCount}, verified ${verified.effectCount}, imports ${lockedIds.length}`,
    )
  }

  await writeAtomic(outputPath, renderEntry(lockedIds))
  console.log(`Generated ${lockedIds.length} static effect imports`)
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
})
